//
//  ClipboardHistoryManager.swift
//  boringNotch
//
//  Keeps a short, in-memory history of copied text. Nothing is written to disk,
//  and items flagged by apps as concealed/transient (e.g. password managers) are ignored.
//

import AppKit
import Combine
import Defaults

@MainActor
final class ClipboardHistoryManager: ObservableObject {
    static let shared = ClipboardHistoryManager()

    struct Entry: Identifiable, Equatable {
        let id = UUID()
        let text: String
        let date: Date
        var isPinned = false
    }

    @Published private(set) var entries: [Entry] = []
    @Published private(set) var lastCopiedID: UUID?

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    private let maxCharacters = 10_000
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private init() {
        lastChangeCount = pasteboard.changeCount
        updateMonitoring()
    }

    // MARK: - Monitoring

    /// Starts or stops polling depending on the user's setting.
    func updateMonitoring() {
        if Defaults[.enableClipboardHistory] {
            guard timer == nil else { return }
            lastChangeCount = pasteboard.changeCount
            let newTimer = Timer(timeInterval: 0.7, repeats: true) { [weak self] _ in
                Task { @MainActor in self?.poll() }
            }
            RunLoop.main.add(newTimer, forMode: .common)
            timer = newTimer
        } else {
            timer?.invalidate()
            timer = nil
        }
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        if let types = pasteboard.types,
           types.contains(where: { ignoredTypes.contains($0.rawValue) }) {
            return
        }
        guard let raw = pasteboard.string(forType: .string) else { return }
        let text = String(raw.prefix(maxCharacters))
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        insert(text)
    }

    private func insert(_ text: String) {
        var pinned = false
        if let index = entries.firstIndex(where: { $0.text == text }) {
            pinned = entries[index].isPinned
            entries.remove(at: index)
        }
        var entry = Entry(text: text, date: Date())
        entry.isPinned = pinned
        entries.insert(entry, at: 0)
        trim()
    }

    private func trim() {
        let limit = max(1, Defaults[.clipboardHistoryLimit])
        var unpinnedSeen = 0
        entries = entries.filter { entry in
            if entry.isPinned { return true }
            unpinnedSeen += 1
            return unpinnedSeen <= limit
        }
    }

    /// Re-applies the history limit after it changes in settings.
    func applyLimitChange() { trim() }

    // MARK: - Actions

    func copy(_ entry: Entry) {
        pasteboard.clearContents()
        pasteboard.setString(entry.text, forType: .string)
        // Avoid re-capturing our own write.
        lastChangeCount = pasteboard.changeCount

        if let index = entries.firstIndex(where: { $0.id == entry.id }), index != 0 {
            let moved = entries.remove(at: index)
            entries.insert(moved, at: 0)
        }

        lastCopiedID = entry.id
        let id = entry.id
        Task { @MainActor [weak self] in
            try? await Task.sleep(for: .seconds(1))
            if self?.lastCopiedID == id { self?.lastCopiedID = nil }
        }
    }

    func togglePin(_ entry: Entry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[index].isPinned.toggle()
        // Keep pinned items at the top.
        entries.sort { lhs, rhs in
            if lhs.isPinned != rhs.isPinned { return lhs.isPinned }
            return lhs.date > rhs.date
        }
        trim()
    }

    func remove(_ entry: Entry) {
        entries.removeAll { $0.id == entry.id }
    }

    func clearUnpinned() {
        entries.removeAll { !$0.isPinned }
    }
}
